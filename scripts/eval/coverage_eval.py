def main():
    kb = KnowledgeBase()
    rows = []
    for n, (mod, q, need) in enumerate(QS, 1):
        try:
            rw = llm.rewrite_query(q, config.DEEPSEEK_API_KEY)
            scen, kw, oral = rw.get("scenario"), rw.get("keywords") or q, rw.get("oral_query") or ""
        except Exception as e:
            print("改写失败", e)
            scen, kw, oral = None, q, ""
        laws, cases = kb.search(kw, scenario=scen, k=5, extra_query=oral)
        rows.append({
            "序号": n, "模块": mod, "问题": q, "场景": scen, "检索词": kw,
            "问题标签": "、".join(tags_of(f"{kw} {oral}")),
            "法条": "；".join(f"{'合同法' if '合同' in l['law'] else '劳动法'}{l['article']}" + ("(关联)" if l.get("_cited") else "") for l in laws),
            "案例": " || ".join(c["title"] for c in cases),
            "库外所需法规": need,
        })
        print(f"{n:02d} [{mod}] {q} | 场景={scen} | 案例{len(cases)}")
    with open(OUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print("已写入", OUT)


if __name__ == "__main__":
    main()
