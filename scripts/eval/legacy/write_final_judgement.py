def main():
    import json
    from testset import QUESTIONS_30, TARGETS_30, QUESTIONS_15, TARGETS_15

    rows = []
    for i, (q, t) in enumerate(zip(QUESTIONS_30, TARGETS_30), 1):
        exp = "、".join(f"{x[0]}第{x[1]}条" for x in t) if t else "边界"
        for ver in ["本地_向量BM25", "线上_纯BM25"]:
            j, reason = J30[(i, ver)]
            rows.append({"测试集": "原30", "题号": i, "版本": ver, "问题": q,
                         "预期依据": exp, "判定结果": j, "判定理由": reason})
    for i, (q, t) in enumerate(zip(QUESTIONS_15, TARGETS_15), 1):
        exp = "、".join(f"{x[0]}第{x[1]}条" for x in t) if t else "边界"
        for ver in ["本地_向量BM25", "线上_纯BM25"]:
            j, reason = J15[(i, ver)]
            rows.append({"测试集": "新15", "题号": i, "版本": ver, "问题": q,
                         "预期依据": exp, "判定结果": j, "判定理由": reason})

    cols = ["测试集", "题号", "版本", "问题", "预期依据", "判定结果", "判定理由"]
    with open(OUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)

    from collections import Counter
    for tag in ["原30", "新15"]:
        for ver in ["本地_向量BM25", "线上_纯BM25"]:
            sub = [r for r in rows if r["测试集"] == tag and r["版本"] == ver]
            c = Counter(r["判定结果"] for r in sub)
            print(f"{tag} {ver}: 正确{c['正确']} 部分正确{c['部分正确']} 错误{c['错误']}")
    print("DONE ->", OUT.name)


if __name__ == "__main__":
    main()
